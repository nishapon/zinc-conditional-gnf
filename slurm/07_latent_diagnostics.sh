#!/bin/bash
#SBATCH --job-name=zinc_latent_diag
#SBATCH --output=outputs/logs/%x_%j.log
#SBATCH --error=outputs/logs/%x_%j.err
#SBATCH --mail-user=ponnambalam@uni-hildesheim.de
#SBATCH --mail-type=END,FAIL
#SBATCH --partition=CPU
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=4
#SBATCH --mem=16G
#SBATCH --time=02:00:00

# ---------------------------------------------------------------------------
# READ-ONLY DIAGNOSTIC of the frozen autoencoder's latent geometry and of the
# molecules we already have. CPU only: it trains nothing and sends nothing to a
# GPU, so it can run while the GPU queue is busy.
#
# Three parts, written to outputs/metrics/latent_diagnostics/:
#   A  embedding covariance spectrum, effective rank, participation ratio and
#      between-dimension correlations, estimated on TRAINING embeddings only;
#   B  decoder robustness measured SEPARATELY along the dominant and the
#      low-variance eigen-directions (plus an isotropic reference and a shared
#      unperturbed baseline), on VALIDATION molecules that never entered the
#      basis estimate;
#   C  QED / rings / aromaticity / bond composition / validity for real
#      validation molecules, the autoencoder's reconstructions of the same
#      molecules, and the molecules already generated by the flow smoke run.
#
# Nothing is modified: the autoencoder is opened read-only (its SHA-256 is
# recorded), the dataset is read-only, the test split is never loaded, and no
# existing checkpoint or output directory is touched.
#
#   SPECTRUM_MOLECULES=20000     training molecules for the covariance
#   ROBUSTNESS_MOLECULES=500     validation molecules per perturbation setting
#   PROFILE_MOLECULES=5000       validation molecules for the real profile
#   RECONSTRUCTION_MOLECULES=2000 validation molecules reconstructed
#   K=5                          eigen-directions in the top / bottom groups
#   GENERATED="name=path,..."    samples.jsonl files to profile (already written)
#
#     sbatch slurm/07_latent_diagnostics.sh
#
# Never run this file with `bash` directly on the master node.
# ---------------------------------------------------------------------------

set -euo pipefail

if [[ -z "${SLURM_JOB_ID:-}" ]]; then
    echo "ERROR: not running under SLURM. Submit with sbatch." >&2
    exit 64
fi

on_error() {
    local rc=$?
    echo "==============================================" >&2
    echo "JOB FAILED  rc=${rc}  line=${1:-?}  command: ${BASH_COMMAND}" >&2
    echo "diagnostic rc: 2=missing checkpoint/data, 4=bad arguments, 1=traceback" >&2
    echo "inspect: sacct -j ${SLURM_JOB_ID} --format=JobID,State,ExitCode,Elapsed,MaxRSS" >&2
    echo "         tail -50 ${OUT:-outputs/metrics/latent_diagnostics}/diagnostics.log" >&2
    echo "==============================================" >&2
}
trap 'on_error $LINENO' ERR

WORKDIR="${SLURM_SUBMIT_DIR:-$HOME/zinc-conditional-gnf}"
cd "${WORKDIR}"

PYTHON="${ZINC_GNF_PYTHON:-}"
if [[ -z "${PYTHON}" ]]; then
    for candidate in "$HOME/miniconda3/envs/zinc_gnf/bin/python" \
                     "$HOME/anaconda3/envs/zinc_gnf/bin/python" \
                     "$HOME/miniforge3/envs/zinc_gnf/bin/python"; do
        if [[ -x "${candidate}" ]]; then PYTHON="${candidate}"; break; fi
    done
fi
if [[ -z "${PYTHON}" || ! -x "${PYTHON}" ]]; then
    echo "ERROR: could not find the python of the Conda env 'zinc_gnf'." >&2
    echo "Resubmit with: sbatch --export=ALL,ZINC_GNF_PYTHON=/path/to/envs/zinc_gnf/bin/python slurm/07_latent_diagnostics.sh" >&2
    exit 65
fi

export PYTHONUNBUFFERED=1
export PYTHONPATH="${WORKDIR}${PYTHONPATH:+:${PYTHONPATH}}"
export OMP_NUM_THREADS=4 MKL_NUM_THREADS=4

DATA_DIR="data/processed/zinc250k_charge_aware_moflow_fixed"
AE_CHECKPOINT="${ZINC_GNF_AE:-outputs/ablation/ae_degree/seed_3/last.pt}"
OUT="outputs/metrics/latent_diagnostics"
SPECTRUM_MOLECULES="${SPECTRUM_MOLECULES:-20000}"
ROBUSTNESS_MOLECULES="${ROBUSTNESS_MOLECULES:-500}"
PROFILE_MOLECULES="${PROFILE_MOLECULES:-5000}"
RECONSTRUCTION_MOLECULES="${RECONSTRUCTION_MOLECULES:-2000}"
K="${K:-5}"
# Molecules already generated by the flow smoke run; skipped automatically if absent.
GENERATED="${GENERATED:-flow_smoke_T0.85=outputs/samples/flow_smoke/T0.85/samples.jsonl,flow_smoke_T1.0=outputs/samples/flow_smoke/T1/samples.jsonl}"
mkdir -p outputs/logs "${OUT}"

echo "=============================================="
echo "Latent geometry and molecular profile diagnostics"
echo "Start time:       $(date -u +%Y-%m-%dT%H:%M:%SZ)"
echo "Job:              ${SLURM_JOB_ID} (${SLURM_JOB_NAME:-?})"
echo "Node:             $(hostname)"
echo "Partition:        ${SLURM_JOB_PARTITION:-unknown} (CPU on purpose)"
echo "CPUs / memory:    ${SLURM_CPUS_PER_TASK:-?} / ${SLURM_MEM_PER_NODE:-?} MB"
echo "Git commit:       $(git rev-parse --short HEAD 2>/dev/null || echo unknown)"
echo "Autoencoder:      ${AE_CHECKPOINT} (read-only, frozen)"
echo "Output:           ${OUT}"
echo "=============================================="
"${PYTHON}" -V

if [[ ! -f "${DATA_DIR}/splits.pkl" ]]; then
    echo "ERROR: ${DATA_DIR}/splits.pkl not found." >&2
    exit 66
fi
if [[ ! -f "${AE_CHECKPOINT}" ]]; then
    echo "ERROR: frozen autoencoder ${AE_CHECKPOINT} not found." >&2
    exit 66
fi

# Dependency preflight: without scipy's MILP the degree-constrained decoder would
# silently fall back to greedy and part B's fallback column would be meaningless.
"${PYTHON}" - <<'PYCHECK'
import sys
import torch, rdkit, numpy, scipy
print("torch", torch.__version__, "| rdkit", rdkit.__version__, "| scipy", scipy.__version__)
try:
    from scipy.optimize import milp
except ImportError as error:
    sys.exit(f"ERROR: scipy.optimize.milp unavailable ({error}); the degree-constrained "
             "decoder would fall back to greedy for every molecule. Install scipy >= 1.9.")
print("dependency check ok")
PYCHECK

# Only pass --generated for files that actually exist, so a missing smoke-run
# sample file degrades to "no generated population" instead of failing the job.
GENERATED_ARGS=()
IFS=',' read -r -a GENERATED_ENTRIES <<< "${GENERATED}"
for ENTRY in "${GENERATED_ENTRIES[@]}"; do
    [[ -z "${ENTRY}" ]] && continue
    GEN_PATH="${ENTRY#*=}"
    if [[ -f "${GEN_PATH}" ]]; then
        GENERATED_ARGS+=(--generated "${ENTRY}")
        echo "will profile generated population: ${ENTRY}"
    else
        echo "note: ${GEN_PATH} not found, that generated population is omitted"
    fi
done

echo
echo "---- diagnostics ----"
srun "${PYTHON}" -u scripts/07_latent_diagnostics.py \
    --ae-checkpoint "${AE_CHECKPOINT}" \
    --data-dir "${DATA_DIR}" \
    --output-dir "${OUT}" \
    --spectrum-molecules "${SPECTRUM_MOLECULES}" \
    --robustness-molecules "${ROBUSTNESS_MOLECULES}" \
    --profile-molecules "${PROFILE_MOLECULES}" \
    --reconstruction-molecules "${RECONSTRUCTION_MOLECULES}" \
    --k "${K}" \
    --batch-size 128 \
    --seed 0 \
    --device cpu \
    "${GENERATED_ARGS[@]+${GENERATED_ARGS[@]}}"

echo "=============================================="
echo "Finished: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
ls -la "${OUT}"
echo "Report:  ${OUT}/diagnostics.txt     (readable tables)"
echo "Data:    ${OUT}/diagnostics.json    (full spectrum and every row)"
echo "Log:     ${OUT}/diagnostics.log"
echo
echo "These are MEASUREMENTS, not a diagnosis. In particular they cannot by themselves"
echo "separate numerical instability from decoder sensitivity from insufficient flow"
echo "training; that needs them read together with the flow's own training log."
echo "=============================================="

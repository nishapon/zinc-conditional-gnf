#!/usr/bin/env python3
"""Stage 7 — latent geometry, direction-resolved robustness and molecular profiles.

A read-only diagnostic. It answers three questions about the FROZEN autoencoder and the
molecules we already have, and it changes nothing:

  A  What does the embedding covariance look like? Eigenvalue spectrum, effective rank,
     participation ratio and the between-dimension correlations that a DIAGONAL whitening
     cannot remove. Estimated on TRAINING embeddings only.

  B  How much displacement can the decoder absorb, separately along the dominant and the
     low-variance eigen-directions, with a shared unperturbed baseline and matched
     magnitudes? Measured on VALIDATION molecules, which never entered the basis estimate.

  C  How do real validation molecules, the autoencoder's reconstructions of those same
     molecules, and molecules already generated by the flow compare on QED (mean, median,
     fraction >= 0.7), rings, aromaticity, bond composition and structural validity?

Nothing is trained; no checkpoint, dataset or earlier output is written. The autoencoder
is opened read-only in eval mode with gradients disabled, and the test split is never
loaded. Results go to --output-dir as diagnostics.json plus a readable diagnostics.txt.

The generated population is read from files that already exist (`samples.jsonl` written
by scripts/05_generate.py); this script never samples a flow itself.

Exit codes: 0 ok; 2 missing checkpoint or data; 4 bad arguments; 1 unexpected.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
import time
import traceback
from typing import Any

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
if str(REPOSITORY_ROOT) not in sys.path:
    sys.path.insert(0, str(REPOSITORY_ROOT))

import numpy as np  # noqa: E402
import torch  # noqa: E402

from zinc_gnf.dataset import (  # noqa: E402
    DatasetFormatError,
    MolecularGraphDataset,
    load_training_splits,
    seeded_subset_indices,
)
from zinc_gnf.latent_geometry import (  # noqa: E402
    DEFAULT_MAGNITUDES,
    anisotropic_robustness,
    covariance_spectrum,
    format_robustness,
    format_spectrum,
    node_embeddings,
)
from zinc_gnf.molecular_profile import (  # noqa: E402
    compare_profiles,
    format_comparison,
    profile_molecules,
)
from zinc_gnf.trainer_autoencoder import load_autoencoder, resolve_device  # noqa: E402
from zinc_gnf.trainer_flow import file_sha256  # noqa: E402
from zinc_gnf.utils.logging import JobLogger  # noqa: E402
from zinc_gnf.utils.runtime import atomic_write_json  # noqa: E402

SPECTRUM_SUBSET_SEED = 4242        # same constant the flow trainer uses for its statistics
EVAL_SUBSET_SEED = 12345           # same validation subset seed as the trainers


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ae-checkpoint", default="outputs/ablation/ae_degree/seed_3/last.pt")
    parser.add_argument("--data-dir", default="data/processed/zinc250k_charge_aware_moflow_fixed")
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("--spectrum-molecules", type=int, default=20000,
                        help="TRAINING molecules used for the covariance estimate")
    parser.add_argument("--robustness-molecules", type=int, default=500,
                        help="VALIDATION molecules per robustness row (each row decodes them all)")
    parser.add_argument("--profile-molecules", type=int, default=5000,
                        help="VALIDATION molecules for the real-population profile")
    parser.add_argument("--reconstruction-molecules", type=int, default=2000,
                        help="VALIDATION molecules reconstructed through the autoencoder")
    parser.add_argument("--k", type=int, default=5,
                        help="how many eigen-directions the top/bottom groups use")
    parser.add_argument("--magnitudes", default=",".join(str(m) for m in DEFAULT_MAGNITUDES))
    parser.add_argument("--generated", action="append", default=[], metavar="NAME=PATH",
                        help="a samples.jsonl already written by scripts/05_generate.py, "
                             "e.g. flow_T0.85=outputs/samples/flow_smoke/T0.85/samples.jsonl")
    parser.add_argument("--generated-decoder", default="degree",
                        choices=("raw", "constrained", "degree"))
    parser.add_argument("--batch-size", type=int, default=128)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--device", choices=("auto", "cpu", "cuda"), default="cpu")
    parser.add_argument("--skip-robustness", action="store_true")
    parser.add_argument("--skip-profiles", action="store_true")
    return parser.parse_args(argv)


def read_generated(path: Path, decoder: str) -> list[str | None]:
    """SMILES of one decoder from a samples.jsonl, keeping invalid samples as None."""
    smiles: list[str | None] = []
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            if not line.strip():
                continue
            record = json.loads(line)
            entry = record.get(decoder)
            if entry is None:
                raise ValueError(f"{path} has no '{decoder}' decoder results")
            smiles.append(entry.get("smiles") if entry.get("valid") else None)
    return smiles


@torch.no_grad()
def reconstruct(model, dataset: MolecularGraphDataset, indices, device, batch_size: int,
                decoder: str) -> list[str | None]:
    """Canonical SMILES of the autoencoder's own reconstructions (free-running)."""
    from zinc_gnf.generation import decode_embeddings

    smiles: list[str | None] = []
    from zinc_gnf.dataset import iter_eval_batches
    order = [int(i) for i in indices]
    for batch in iter_eval_batches(dataset, batch_size, order):
        batch = batch.to(device)
        embeddings = model.encode(batch)
        counts = [int(n) for n in batch.n_node]
        decoders = ("degree",) if decoder == "degree" and model.config.degree_head else ("constrained",)
        records = decode_embeddings(model, embeddings, counts, decoders=decoders)
        for record in records:
            entry = record[decoders[0]]
            smiles.append(entry["smiles"] if entry["valid"] else None)
    return smiles


def main(argv: list[str] | None = None) -> int:
    arguments = parse_args(argv)
    output = Path(arguments.output_dir)
    try:
        magnitudes = [float(m) for m in str(arguments.magnitudes).split(",") if m.strip()]
        if not magnitudes:
            raise ValueError("no magnitudes given")
        if arguments.k < 1:
            raise ValueError("--k must be >= 1")
        generated_paths: dict[str, Path] = {}
        for item in arguments.generated:
            name, separator, raw = item.partition("=")
            if not separator:
                raise ValueError(f"--generated expects NAME=PATH, got {item!r}")
            generated_paths[name] = Path(raw)
        output.mkdir(parents=True, exist_ok=True)
        logger = JobLogger("diagnostics", output, filename="diagnostics.log")
    except (OSError, ValueError) as error:
        print(f"FATAL: {error}", file=sys.stderr, flush=True)
        return 4

    try:
        started = time.perf_counter()
        device = resolve_device(arguments.device)
        checkpoint = Path(arguments.ae_checkpoint)
        if not checkpoint.exists():
            raise FileNotFoundError(f"autoencoder checkpoint not found: {checkpoint}")
        model, probe = load_autoencoder(checkpoint, device=device)
        for parameter in model.parameters():
            parameter.requires_grad_(False)
        model.eval()

        train_records, val_records, fingerprint = load_training_splits(arguments.data_dir)
        train_set = MolecularGraphDataset(train_records)
        val_set = MolecularGraphDataset(val_records)
        del train_records, val_records

        logger.header("Latent geometry and molecular profile diagnostics")
        logger.info(f"autoencoder={checkpoint} sha256={file_sha256(checkpoint)[:16]} "
                    f"step={probe.get('step')} degree_head={model.config.degree_head} "
                    f"embedding_dim={model.config.node_embedding_dim}")
        logger.info(f"data={arguments.data_dir} train={len(train_set):,} val={len(val_set):,} "
                    f"(test split NOT loaded) protocol={fingerprint.get('split_protocol')}")
        logger.info(f"device={device} k={arguments.k} magnitudes={magnitudes}")

        result: dict[str, Any] = {
            "autoencoder": {"checkpoint": str(checkpoint), "sha256": file_sha256(checkpoint),
                            "step": probe.get("step"),
                            "model_config": model.config.to_dict()},
            "data": {k: fingerprint.get(k) for k in
                     ("representation", "split_protocol", "counts", "counts_digest")},
            "settings": {"spectrum_molecules": arguments.spectrum_molecules,
                         "robustness_molecules": arguments.robustness_molecules,
                         "profile_molecules": arguments.profile_molecules,
                         "reconstruction_molecules": arguments.reconstruction_molecules,
                         "k": arguments.k, "magnitudes": magnitudes, "seed": arguments.seed,
                         "device": str(device),
                         "spectrum_split": "train", "robustness_split": "validation",
                         "profile_split": "validation"},
        }
        report: list[str] = []

        # --- A. spectrum, on TRAINING embeddings only -------------------------------
        spectrum_indices = seeded_subset_indices(len(train_set), arguments.spectrum_molecules,
                                                 SPECTRUM_SUBSET_SEED)
        logger.info(f"[A] encoding {len(spectrum_indices):,} TRAINING molecules for the covariance")
        embeddings = node_embeddings(model, train_set, indices=spectrum_indices, device=device,
                                     batch_size=arguments.batch_size)
        summary, eigenvalues, eigenvectors = covariance_spectrum(embeddings)
        result["spectrum"] = summary
        result["spectrum"]["molecules"] = len(spectrum_indices)
        report.append(format_spectrum(summary))
        logger.info(f"[A] participation ratio {summary['participation_ratio']:.2f}/"
                    f"{summary['dimension']}, effective rank 99% = {summary['effective_rank_99']}, "
                    f"max |r| = {summary['max_absolute_correlation']:.3f}")
        del embeddings

        # --- B. direction-resolved robustness, on VALIDATION ------------------------
        if not arguments.skip_robustness:
            robustness_indices = seeded_subset_indices(len(val_set), arguments.robustness_molecules,
                                                       EVAL_SUBSET_SEED)
            logger.info(f"[B] robustness on {len(robustness_indices):,} VALIDATION molecules "
                        f"x {len(magnitudes) * 6} perturbation settings")
            rows = anisotropic_robustness(model, val_set, eigenvalues=eigenvalues,
                                          eigenvectors=eigenvectors, indices=robustness_indices,
                                          device=device, magnitudes=magnitudes, k=arguments.k,
                                          seed=arguments.seed, batch_size=arguments.batch_size)
            result["robustness"] = rows
            report.append("")
            report.append(format_robustness(rows))
            baseline = rows[0]
            decoder_key = "degree" if "degree" in baseline else "constrained"
            logger.info(f"[B] unperturbed baseline: exact "
                        f"{baseline[decoder_key]['exact_molecule_match']:.4f}, fallback "
                        f"{baseline.get('degree_fallback_rate', float('nan')):.4f}")

        # --- C. molecular profiles --------------------------------------------------
        if not arguments.skip_profiles:
            profile_indices = seeded_subset_indices(len(val_set), arguments.profile_molecules,
                                                    EVAL_SUBSET_SEED)
            logger.info(f"[C] profiling {len(profile_indices):,} real VALIDATION molecules")
            profiles = [profile_molecules((val_set.smiles[i] for i in profile_indices),
                                          name="real_validation")]
            reconstruction_indices = seeded_subset_indices(
                len(val_set), arguments.reconstruction_molecules, EVAL_SUBSET_SEED)
            logger.info(f"[C] reconstructing {len(reconstruction_indices):,} VALIDATION molecules")
            profiles.append(profile_molecules(
                reconstruct(model, val_set, reconstruction_indices, device,
                            arguments.batch_size, arguments.generated_decoder),
                name="ae_reconstruction"))
            # the real molecules behind the reconstruction subset, as a matched reference
            profiles.append(profile_molecules(
                (val_set.smiles[i] for i in reconstruction_indices),
                name="real_matched_subset"))
            for name, path in generated_paths.items():
                if not path.exists():
                    raise FileNotFoundError(f"generated samples not found: {path}")
                logger.info(f"[C] profiling generated population {name} from {path}")
                profiles.append(profile_molecules(
                    read_generated(path, arguments.generated_decoder), name=name))
            comparison = compare_profiles(profiles)
            result["profiles"] = comparison
            report.append("")
            report.append(format_comparison(comparison))
            real = comparison["profiles"]["real_validation"]
            logger.info(f"[C] real validation QED mean {real['qed']['mean']:.4f}, "
                        f"fraction >= 0.7 {real['qed_at_least_0p7']:.4f}")

        result["seconds"] = time.perf_counter() - started
        atomic_write_json(result, output / "diagnostics.json")
        text = "\n".join(report) + "\n"
        (output / "diagnostics.txt").write_text(text, encoding="utf-8")
        print(text, flush=True)
        logger.info(f"wrote {output / 'diagnostics.json'} and diagnostics.txt "
                    f"in {result['seconds']:.1f}s")
        logger.info("NOTE: these are measurements only. They do not by themselves identify a "
                    "cause; numerical instability, decoder sensitivity and insufficient flow "
                    "training have to be told apart by comparing them with the flow's own logs.")
    except FileNotFoundError as error:
        print(f"FATAL: {error}", file=sys.stderr, flush=True)
        return 2
    except (DatasetFormatError, ValueError) as error:
        print(f"FATAL: {type(error).__name__}: {error}", file=sys.stderr, flush=True)
        return 4
    except Exception:  # noqa: BLE001
        print("FATAL: unexpected error\n" + traceback.format_exc(), file=sys.stderr, flush=True)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

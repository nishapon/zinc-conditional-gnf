#!/usr/bin/env python3
"""Preflight: verify paths, read ACTUAL checkpoint settings, find or export a baseline.

Run this first on the cluster. It touches no GPU and writes no large artefact. It answers
four questions before any expensive job:

  1. Do the configured data, scaler, decoder and flow checkpoints exist and load?
  2. What settings did the conditional flow ACTUALLY train with? Read from the
     checkpoint's own `flow_config` / `train_config`, never inferred from a YAML.
  3. Is there a compatible matched baseline inside the supplied search directories?
  4. If not, export a matched N-ONLY training config derived from the conditional
     checkpoint's own settings, changing only the conditioning.

Exit codes: 0 ok; 2 missing input; 3 incompatible; 4 bad arguments; 1 unexpected.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
import traceback

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from zinc_gnf.eval_support import STRUCTURAL_SIZE_NOTE  # noqa: E402

# Keys that may differ between the baseline and the conditional model. Everything else
# must match, or the comparison measures more than conditioning.
CONDITIONING_KEYS = ("condition_features", "condition_embedding_dim",
                     "condition_hidden_dim")


def load_config(path):
    text = Path(path).read_text()
    return json.loads(text)


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", default="configs/cluster.json")
    parser.add_argument("--export-baseline-config",
                        default="configs/generated/baseline_n_only.yaml")
    parser.add_argument("--device", default="cpu")
    return parser.parse_args(argv)


def yaml_scalar(value):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(json.dumps(v) for v in value) + "]"
    if isinstance(value, str):
        return json.dumps(value)
    return repr(value)


def export_baseline_yaml(path, *, flow_config, train_config, output_dir, source):
    """Write a matched N-only config from the conditional checkpoint's OWN settings.

    Nothing is assumed: every architecture and training value is copied from the parent
    checkpoint's stored configuration. The ONLY edits are `condition_features` (QED
    removed, N kept) and `output_dir`.
    """
    flow = dict(flow_config)
    train = dict(train_config or {})
    original = list(flow.get("condition_features") or [])
    if "n" not in original:
        raise ValueError(f"the conditional checkpoint conditions on {original}; an "
                         f"N-only baseline is only matched if the parent also uses 'n'")
    flow["condition_features"] = ["n"]
    # Drop any key the current FlowConfig/FlowTrainConfig does not accept. A parent
    # trained with extra QED objectives (e.g. contrastive terms) stores fields the
    # evaluation trainer rejects at construction, and the exported baseline must be
    # loadable by scripts/04_train_flow.py unchanged.
    from zinc_gnf.flow import FlowConfig
    from zinc_gnf.trainer_flow import FlowTrainConfig

    dropped = {"flow": [], "training": []}
    for key in [k for k in flow if k not in FlowConfig.__dataclass_fields__]:
        dropped["flow"].append(key)
        flow.pop(key)
    for key in [k for k in train if k not in FlowTrainConfig.__dataclass_fields__]:
        dropped["training"].append(key)
        train.pop(key)
    # Also drop anything QED-specific that survives the field check: an N-only baseline
    # must not carry a QED knob, even an accepted one.
    for key in [k for k in list(flow) + list(train) if "qed" in k.lower()]:
        dropped["flow" if key in flow else "training"].append(key)
        flow.pop(key, None)
        train.pop(key, None)
    train["output_dir"] = output_dir
    # Absolute paths: a training job submitted from another directory must still find
    # the data and the frozen decoder.
    for key in ("data_dir", "ae_checkpoint"):
        if train.get(key):
            train[key] = str(Path(train[key]).resolve())
    lines = [
        "# ============================================================================",
        "# MATCHED N-ONLY BASELINE, generated by scripts/47_cluster_preflight.py.",
        "#",
        f"# Derived from: {source}",
        f"# Parent condition_features: {original}  ->  baseline: ['n']",
        "#",
        "# Every architecture and training value below was COPIED from that checkpoint's",
        "# own stored flow_config / train_config. Nothing was inferred from another YAML.",
        "# The only edits are condition_features (QED removed, N kept) and output_dir.",
        "#",
        "# This holds LEARNED N conditioning fixed and removes only QED, so the",
        "# comparison isolates QED conditioning. Label it 'matched N-only baseline',",
        "# never 'unconditional': it still receives N through FiLM and the prior, and",
        "# both models receive the atom count structurally in any case.",
        "# ============================================================================",
        "",
        "flow:",
    ]
    for key in sorted(flow):
        lines.append(f"  {key}: {yaml_scalar(flow[key])}")
    lines += ["", "training:"]
    for key in sorted(train):
        lines.append(f"  {key}: {yaml_scalar(train[key])}")
    lines.append("")
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))
    return {"path": str(path), "condition_features": ["n"],
            "dropped_unsupported_or_qed_fields": dropped,
            "absolute_paths": {k: train.get(k) for k in ("data_dir", "ae_checkpoint")},
            "parent_condition_features": original,
            "copied_flow_keys": sorted(flow), "copied_training_keys": sorted(train)}


def describe_checkpoint(path, device):
    from zinc_gnf.trainer_flow import file_sha256, load_flow

    flow, probe = load_flow(path, device=device)
    train_config = probe.get("train_config") or {}
    return flow, {
        "path": str(path),
        "sha256": file_sha256(path),
        "step": probe.get("step"),
        "best_step": probe.get("best_step"),
        "best_loss": probe.get("best_loss"),
        "flow_config": probe["flow_config"],
        "train_config": train_config,
        "training_seed": train_config.get("seed"),
        "batch_size": train_config.get("batch_size"),
        "max_steps": train_config.get("max_steps"),
        "learning_rate": train_config.get("learning_rate"),
        "condition_features": list(probe["flow_config"].get("condition_features") or []),
        "node_embedding_dim": probe["flow_config"].get("node_embedding_dim"),
        "num_blocks": probe["flow_config"].get("num_blocks"),
        "node_autoregressive": probe["flow_config"].get("node_autoregressive"),
        "autoencoder_recorded": probe.get("autoencoder"),
        "data_fingerprint": probe.get("data_fingerprint"),
        "parameters": flow.num_parameters(),
    }


def compatibility(conditional, candidate):
    """Is `candidate` a matched baseline for `conditional`?"""
    left, right = dict(conditional["flow_config"]), dict(candidate["flow_config"])
    differences = {k: {"conditional": left.get(k), "candidate": right.get(k)}
                   for k in sorted(set(left) | set(right))
                   if str(left.get(k)) != str(right.get(k))}
    confounds = {k: v for k, v in differences.items() if k not in CONDITIONING_KEYS}
    features = list(right.get("condition_features") or [])
    return {
        "candidate": candidate["path"],
        "condition_features": features,
        "is_n_only": features == ["n"],
        "is_unconditional": features == [],
        "remaining_differences": confounds,
        "matched": not confounds and features in (["n"], []),
        "label": ("matched N-only baseline" if features == ["n"] and not confounds else
                  "unconditional baseline (also removes learned N conditioning)"
                  if features == [] and not confounds else
                  "NOT matched: differs in " + ", ".join(sorted(confounds))),
    }


def main(argv=None) -> int:
    args = parse_args(argv)
    try:
        config = load_config(args.config)
    except (OSError, ValueError) as error:
        print(f"FATAL: cannot read --config {args.config}: {error}", file=sys.stderr)
        return 4

    report = {"config_file": str(args.config), "config": config,
              "structural_size_note": STRUCTURAL_SIZE_NOTE}
    try:
        paths = config["paths"]
        required = {
            "dataset": Path(paths["data_dir"]) / "splits.pkl",
            "scaler": Path(paths["data_dir"]) / "scaler.json",
            "decoder": Path(paths["ae_checkpoint"]),
            "conditional_flow": Path(paths["conditional_checkpoint"]),
        }
        missing = {name: str(p) for name, p in required.items() if not p.is_file()}
        report["files"] = {name: {"path": str(p), "present": p.is_file()}
                           for name, p in required.items()}
        if missing:
            print("FATAL: missing required files:", file=sys.stderr)
            for name, p in missing.items():
                print(f"  {name}: {p}", file=sys.stderr)
            Path(config["paths"]["results_dir"]).mkdir(parents=True, exist_ok=True)
            (Path(config["paths"]["results_dir"]) / "preflight.json").write_text(
                json.dumps(report, indent=2, default=str))
            return 2

        from zinc_gnf.trainer_autoencoder import load_autoencoder
        from zinc_gnf.trainer_flow import file_sha256

        results_dir = Path(paths["results_dir"])
        results_dir.mkdir(parents=True, exist_ok=True)

        conditional, cond_info = describe_checkpoint(paths["conditional_checkpoint"],
                                                     args.device)
        report["conditional"] = cond_info
        if set(cond_info["condition_features"]) != {"n", "qed"}:
            print(f"FATAL: conditional checkpoint conditions on "
                  f"{cond_info['condition_features']}, expected n and qed",
                  file=sys.stderr)
            return 3

        autoencoder, ae_probe = load_autoencoder(paths["ae_checkpoint"],
                                                 device=args.device)
        report["decoder"] = {
            "path": paths["ae_checkpoint"],
            "sha256": file_sha256(paths["ae_checkpoint"]),
            "node_embedding_dim": autoencoder.config.node_embedding_dim,
            "degree_head": bool(autoencoder.config.degree_head),
            "symmetry_noise_dim": autoencoder.config.symmetry_noise_dim,
            "step": ae_probe.get("step"),
        }
        problems = []
        if autoencoder.config.node_embedding_dim != conditional.config.node_embedding_dim:
            problems.append(
                f"decoder width {autoencoder.config.node_embedding_dim} != flow "
                f"node_embedding_dim {conditional.config.node_embedding_dim}")
        if not autoencoder.config.degree_head:
            problems.append(
                "decoder has NO degree head, so the degree-constrained ('native "
                "corrected') decoder cannot run; set headline_decoder to 'constrained' "
                "or supply the degree-head autoencoder")
        recorded = (cond_info.get("autoencoder_recorded") or {}).get("sha256")
        if recorded and recorded != report["decoder"]["sha256"]:
            problems.append(
                f"the flow checkpoint recorded decoder sha256 {str(recorded)[:16]} but "
                f"the supplied decoder is {report['decoder']['sha256'][:16]}; the flow's "
                f"density is defined by its own encoder")
        report["compatibility_problems"] = problems

        # ---- baseline discovery, ONLY inside the supplied directories ----
        search = [Path(d) for d in config.get("baseline_search_dirs", [])]
        candidates = []
        for directory in search:
            if not directory.is_dir():
                candidates.append({"directory": str(directory), "present": False})
                continue
            for found in sorted(directory.rglob("*.pt")):
                if found.resolve() == Path(paths["conditional_checkpoint"]).resolve():
                    continue
                try:
                    _, info = describe_checkpoint(found, args.device)
                except Exception as error:  # noqa: BLE001 - a bad .pt must not abort
                    candidates.append({"candidate": str(found),
                                       "error": f"{type(error).__name__}: {error}"})
                    continue
                candidates.append(compatibility(cond_info, info))
        report["baseline_search"] = {"directories": [str(d) for d in search],
                                     "candidates": candidates}
        matched = [c for c in candidates if c.get("matched")]
        n_only = [c for c in matched if c.get("is_n_only")]
        report["baseline_found"] = bool(matched)
        report["baseline_choice"] = (n_only[0] if n_only else
                                     matched[0] if matched else None)

        if not n_only:
            default_out = str(Path(paths.get("baseline_output_dir",
                                             "outputs/checkpoints/flow_n_only")))
            report["exported_baseline_config"] = export_baseline_yaml(
                args.export_baseline_config,
                flow_config=cond_info["flow_config"],
                train_config=cond_info["train_config"],
                output_dir=default_out,
                source=f"{paths['conditional_checkpoint']} "
                       f"(sha256 {cond_info['sha256'][:16]})")
            report["baseline_action"] = (
                "NO matched N-only baseline was found in the supplied directories. A "
                "matched N-only training config has been exported; train it with "
                "scripts/04_train_flow.py --config <that file>. Its budget is copied "
                "from the parent checkpoint, so expect the same cost as the original "
                "conditional run.")
        else:
            report["baseline_action"] = (
                f"matched N-only baseline available: {n_only[0]['candidate']}")

        out = results_dir / "preflight.json"
        out.write_text(json.dumps(report, indent=2, default=str))
        print(json.dumps({k: report[k] for k in
                          ("files", "compatibility_problems", "baseline_found",
                           "baseline_action")}, indent=2, default=str))
        print(f"\nconditional checkpoint ACTUAL settings (from its own metadata):")
        for key in ("node_embedding_dim", "num_blocks", "node_autoregressive",
                    "condition_features", "training_seed", "batch_size", "max_steps",
                    "learning_rate", "step", "parameters"):
            print(f"  {key:22s} {cond_info[key]}")
        print(f"\n{STRUCTURAL_SIZE_NOTE}")
        print(f"\nwrote {out}")
        if problems:
            print("\nFATAL: compatibility problems above must be resolved first.",
                  file=sys.stderr)
            return 3
        return 0
    except FileNotFoundError as error:
        print(f"FATAL: {error}", file=sys.stderr)
        return 2
    except (ValueError, KeyError) as error:
        print(f"FATAL (configuration or compatibility): {error}", file=sys.stderr)
        return 3
    except Exception:  # noqa: BLE001
        print("FATAL: unexpected\n" + traceback.format_exc(), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
